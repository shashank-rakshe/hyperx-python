"""
Repo packs: every git repo you share makes ShipBrain know more, without making the model bigger.

A repo is turned into ONE small compressed file, packs/<name>.sbpack (gzip JSON), holding its docs and code cut into
search chunks. The knowledge base loads packs next to your own files, so answers can cite e.g. [text-to-cad:README.md#3].
A modest number of verified training samples can be made from packs with training/repo_tasks.py.

  python -m shipbrain.repopack build --repo https://github.com/earthtojake/text-to-cad --repo URL2 --out packs/
  python -m shipbrain.repopack add https://github.com/owner/repo --out packs/        # one more repo
  python -m shipbrain.repopack list packs/

Licence check first (the LICENSE files of the repo are read):
  MIT, Apache-2.0, BSD, ISC, Unlicense, CC-BY, CC-BY-SA (docs)  -> allowed (attribution goes to packs/NOTICE.md)
  AGPL / GPL / LGPL / MPL, "not open source", no licence, unknown -> refused, with the reason in plain English.
  --private-only builds a refused repo anyway as <name>.private.sbpack, marked "do not use for training / do not
  redistribute" (repo_tasks.py skips it; keep it out of git).

What goes in: docs (.md .rst .txt .html) cut per heading, code (.py .rs .ts .tsx .js .jsx .mjs) cut per function /
class / item, JSON schemas and examples. What is dropped: vendored and third-party folders (also any sub-folder with its
own licence from another copyright holder), minified, generated, binary, lock and huge files, licence texts, and
near-duplicate chunks (MinHash over word shingles). A size budget per repo (--max-kb of text) keeps packs small; READMEs
and docs come first, then examples, then source, then tests.
"""
