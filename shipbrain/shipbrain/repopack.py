# ====================================================================== licences
_PATTERNS = [   # (spdx, kind, regex) - first match per file wins; order matters (AGPL/LGPL before GPL)
    ('AGPL-3.0', 'copyleft', r'GNU AFFERO GENERAL PUBLIC LICENSE'),
    ('LGPL', 'copyleft', r'GNU LESSER GENERAL PUBLIC LICENSE|GNU LIBRARY GENERAL PUBLIC'),
    ('GPL', 'copyleft', r'GNU GENERAL PUBLIC LICENSE'),
    ('MPL-2.0', 'copyleft', r'Mozilla Public License'),
    ('EUPL', 'copyleft', r'European Union Public Licen[cs]e'),
    ('SSPL', 'copyleft', r'Server Side Public License'),
    ('CC-BY-NC', 'restricted', r'Attribution-NonCommercial|creativecommons\.org/licenses/by-nc'),
    ('CC-BY-ND', 'restricted', r'Attribution-NoDerivatives|creativecommons\.org/licenses/by-nd'),
    ('CC-BY-SA-4.0', 'permissive', r'Attribution-ShareAlike 4\.0|creativecommons\.org/licenses/by-sa/4\.0'),
    ('CC-BY-SA', 'permissive', r'Attribution-ShareAlike|creativecommons\.org/licenses/by-sa'),
    ('CC-BY-4.0', 'permissive', r'Attribution 4\.0 International|creativecommons\.org/licenses/by/4\.0'),
    ('CC0-1.0', 'permissive', r'CC0 1\.0|Creative Commons Zero'),
    ('Apache-2.0', 'permissive', r'Apache License,?\s+Version 2\.0'),
    ('MIT', 'permissive', r'Permission is hereby granted, free of charge'),
    ('BSD', 'permissive', r'Redistribution and use in source and binary forms'),
    ('ISC', 'permissive', r'Permission to use, copy, modify, and(/or)? distribute this software for any purpose'),
    ('Unlicense', 'permissive', r'This is free and unencumbered software released into the public domain'),
    ('Zlib', 'permissive', r"This software is provided 'as-is', without any express or implied"),
    ('proprietary', 'restricted', r'not open source|proprietary licen[cs]e|confidential and proprietary'),
]
_SPDX_KIND = {'MIT': 'permissive', 'APACHE-2.0': 'permissive', 'BSD-2-CLAUSE': 'permissive', 'BSD-3-CLAUSE': 'permissive',
              'ISC': 'permissive', 'UNLICENSE': 'permissive', 'CC-BY-4.0': 'permissive', 'CC-BY-SA-4.0': 'permissive',
              'CC0-1.0': 'permissive', '0BSD': 'permissive', 'ZLIB': 'permissive'}
WHY = {'copyleft': 'is a copyleft licence: anything built from it (also a trained model or a pack you share) may have to be '
                   'released under the same licence, so it is not used automatically',
       'restricted': 'does not allow free reuse (non-commercial, no-derivatives or "not open source")',
       'unknown': 'could not be recognised, so it is treated as "all rights reserved"'}


_RANK = {'permissive': 0, 'unknown': 1, 'restricted': 2, 'copyleft': 3}


def classify_licence(text):
    """licence text -> (spdx id(s), 'permissive' | 'copyleft' | 'restricted' | 'unknown'). A file naming several
    licences (e.g. MIT for code + CC BY 4.0 for data) gives all of them; the strictest one sets the kind."""
    head = (text or '')[:20000]
    hits = []
    for spdx, kind, rx in _PATTERNS:
        if spdx == 'GPL' and any(h[0] in ('AGPL-3.0', 'LGPL') for h in hits):
            continue                                       # AGPL / LGPL texts quote the GPL
        if re.search(rx, head, re.I | re.M) and not any(spdx.startswith(h[0]) or h[0].startswith(spdx) for h in hits):
            hits.append((spdx, kind))
    if hits:
        return ' + '.join(h[0] for h in hits), max((h[1] for h in hits), key=_RANK.get)
    m = re.search(r'SPDX-License-Identifier:\s*([\w.\-+ ()]+)', head)
    if m:
        return spdx_kind(m.group(1))
    return 'unknown', 'unknown'


def spdx_kind(expr):
    """'MIT OR Apache-2.0' -> ('MIT OR Apache-2.0', 'permissive'); any permissive alternative of an OR is enough"""
    expr = expr.strip().strip('()')
    alts = [a.strip(' ()') for a in re.split(r'\s+OR\s+|/', expr, flags=re.I)]
    kinds = []
    for a in alts:
        parts = [p.strip(' ()') for p in re.split(r'\s+AND\s+', a, flags=re.I)]
        ks = [_SPDX_KIND.get(p.upper(), 'copyleft' if re.search(r'GPL|MPL|EUPL', p, re.I) else 'unknown') for p in parts]
        kinds.append('permissive' if all(k == 'permissive' for k in ks) else next(k for k in ks if k != 'permissive'))
    return expr, ('permissive' if 'permissive' in kinds else kinds[0])


def copyright_lines(text):
    """'Copyright (c) 2026 Name' lines (a year must follow the mark, so licence boilerplate is not picked up)"""
    out = []
    for line in (text or '').splitlines()[:400]:
        s = line.strip().lstrip('#/*- ').strip().rstrip('.')
        if re.match(r'(copyright\s*(\(c\)|©)?|\(c\)|©)\s*\d{4}', s, re.I) and len(s) < 200 and s not in out:
            out.append(s)
    return out


def check_licence(files):
    """files: {filename: text} of the licence files found in the repo root (or a single text).
    Returns {'allowed', 'license', 'kind', 'reason', 'attribution'}: allowed only if at least one permissive licence is
    found and no file is copyleft / restricted (dual 'MIT OR Apache-2.0' repos have two permissive files)."""
    if isinstance(files, str):
        files = {'LICENSE': files}
    found = []
    for name, text in sorted(files.items()):
        if name.startswith('@spdx:'):
            found.append(spdx_kind(text) + (name,))
        else:
            found.append(classify_licence(text) + (name,))
    attribution = []
    for name, text in sorted(files.items()):
        if not name.startswith('@spdx:'):
            attribution += [c for c in copyright_lines(text) if c not in attribution]
    if not found:
        return {'allowed': False, 'license': 'none', 'kind': 'none', 'attribution': attribution,
                'reason': 'No licence file was found. Without a licence nobody may copy or reuse the code (all rights '
                          'reserved), so it is not packed. Use --private-only for your own private use only.'}
    perm = [f for f in found if f[1] == 'permissive']
    bad = [f for f in found if f[1] != 'permissive']
    lic = ' + '.join(dict.fromkeys(f[0] for f in (perm or found)))
    if perm and not bad:
        sa = any('SA' in f[0] for f in perm)
        return {'allowed': True, 'license': lic, 'kind': 'permissive', 'attribution': attribution,
                'reason': f'{lic} is a permissive licence: allowed with attribution (kept in NOTICE.md)'
                          + ('; share-alike: text derived from it stays CC BY-SA' if sa else '') + '.'}
    f = bad[0]
    extra = f' (it also has {", ".join(p[0] for p in perm)}, but the {f[0]} part decides)' if perm else ''
    return {'allowed': False, 'license': ' + '.join(dict.fromkeys(x[0] for x in found)), 'kind': f[1], 'attribution': attribution,
            'reason': f'{f[2].removeprefix("@spdx:")}: ' + ('the licence ' if f[0] == 'unknown' else f'{f[0]} ')
                      + f'{WHY.get(f[1], WHY["unknown"])}{extra}. Not packed. '
                      f'Use --private-only to build it for your own private use only (never for training or sharing).'}


def _licence_files(paths):
    """root-level licence-like files of a repo listing"""
    return [p for p in paths if '/' not in p and LICENCE_FILE.match(p)]


def _manifest_spdx(tree, paths):
    """fallback when there is no LICENSE file: package.json / pyproject.toml / Cargo.toml licence field"""
    for p in ('package.json', 'pyproject.toml', 'Cargo.toml', 'setup.cfg'):
        if p in paths:
            t = tree.read(p).decode('utf-8', 'replace')
            m = (re.search(r'"license"\s*:\s*"([^"]+)"', t) if p.endswith('.json') else
                 re.search(r'^\s*license\s*=\s*(?:\{\s*text\s*=\s*)?"([^"]+)"', t, re.M))
            if m:
                return m.group(1)
    return None


# ====================================================================== reading a repo
class DirTree:
    """a plain folder (not a git repo)"""
    def __init__(self, root):
        self.root = os.path.abspath(root)

    def files(self):
        out = []
        for r, ds, fs in os.walk(self.root):
            ds[:] = sorted(d for d in ds if d != '.git')
            for f in sorted(fs):
                p = os.path.join(r, f)
                if os.path.islink(p):
                    continue
                out.append((os.path.relpath(p, self.root).replace(os.sep, '/'), os.path.getsize(p)))
        return out

    def read(self, rel):
        with open(os.path.join(self.root, rel), 'rb') as f:
            return f.read()

    def close(self):
        pass


class GitTree:
    """files of one commit, read from git objects (no checkout, nothing executed; blobs left out by a partial clone
    are reported as huge and never fetched)"""
    def __init__(self, root, rev='HEAD'):
        self.root, self.rev = root, rev
        self.commit = _git(root, 'rev-parse', rev).strip()
        self._cat = None
        self._sizes = {}

    def files(self):
        raw = subprocess.run(['git', '-C', self.root, 'ls-tree', '-r', '-z', '--full-tree', self.commit],
                             capture_output=True, check=True).stdout.decode('utf-8', 'replace')
        missing = set()
        try:                                       # blobs not downloaded (partial clone): list them without fetching
            rl = subprocess.run(['git', '-C', self.root, 'rev-list', '--objects', '--missing=print', self.commit],
                                capture_output=True, env=_git_env(), timeout=600).stdout.decode('utf-8', 'replace')
            missing = {l[1:].split()[0] for l in rl.splitlines() if l.startswith('?')}
        except Exception:
            pass
        out, self._oid = [], {}
        for ent in raw.split('\0'):
            if not ent:
                continue
            meta, path = ent.split('\t', 1)
            mode, typ, oid = meta.split()
            if typ != 'blob' or mode == '120000':        # submodules, symlinks
                continue
            self._oid[path] = oid
            out.append((path, None if oid not in missing else MAX_FILE * 100))
        return out

    def read(self, rel):
        if self._cat is None:
            self._cat = subprocess.Popen(['git', '-C', self.root, 'cat-file', '--batch'], stdin=subprocess.PIPE,
                                         stdout=subprocess.PIPE, env=_git_env())
        self._cat.stdin.write((self._oid[rel] + '\n').encode())
        self._cat.stdin.flush()
        head = self._cat.stdout.readline().decode().split()
        if len(head) < 3 or head[1] != 'blob':
            raise IOError(f'cannot read {rel}')
        n = int(head[2])
        data = self._cat.stdout.read(n)
        self._cat.stdout.read(1)
        return data

    def close(self):
        if self._cat:
            self._cat.stdin.close()
            self._cat.wait(timeout=30)
            self._cat = None


def _git_env():
    return dict(os.environ, GIT_NO_LAZY_FETCH='1', GIT_TERMINAL_PROMPT='0')


def _git(root, *args, timeout=600):
    return subprocess.run(['git', '-C', root, *args], capture_output=True, text=True, check=True, timeout=timeout,
                          env=_git_env()).stdout


def repo_name(src):
    s = src.rstrip('/').removesuffix('.git')
    return re.sub(r'[^A-Za-z0-9_.\-]', '_', s.replace('\\', '/').split('/')[-1]) or 'repo'


def is_url(src):
    return bool(re.match(r'(https?|git|ssh)://|git@', src))


def open_repo(src, cache_dir=None, log=print):
    """URL -> shallow clone (no checkout) in the cache; local git folder -> its HEAD; plain folder -> walked.
    Returns (tree, url, commit)."""
    if is_url(src):
        cache_dir = cache_dir or os.environ.get('SHIPBRAIN_REPO_CACHE') or os.path.join(os.path.expanduser('~'), '.cache', 'shipbrain', 'repos')
        dest = os.path.join(cache_dir, hashlib.sha1(src.encode()).hexdigest()[:8] + '_' + repo_name(src))
        rev = 'HEAD'
        if os.path.isdir(os.path.join(dest, '.git')) or os.path.exists(os.path.join(dest, 'HEAD')):
            try:
                _git(dest, 'fetch', '--depth', '1', 'origin', 'HEAD')
                rev = 'FETCH_HEAD'
            except Exception:
                log(f'  (could not update {src}; using the cached copy)')
        else:
            os.makedirs(cache_dir, exist_ok=True)
            log(f'  cloning {src} (shallow, text only) ...')
            base = ['git', 'clone', '--depth', '1', '--no-checkout', '--quiet']
            try:
                subprocess.run(base + [f'--filter=blob:limit={MAX_FILE}', src, dest], check=True, capture_output=True,
                               timeout=1800, env=_git_env())
            except subprocess.CalledProcessError:            # server without partial clone
                subprocess.run(base + [src, dest], check=True, capture_output=True, timeout=1800, env=_git_env())
        t = GitTree(dest, rev)
        return t, src, t.commit
    root = os.path.abspath(src)
    if not os.path.isdir(root):
        raise FileNotFoundError(src)
    try:
        t = GitTree(root)
        try:
            url = _git(root, 'remote', 'get-url', 'origin').strip()
        except Exception:
            url = root
        return t, re.sub(r'\.git$', '', url), t.commit
    except Exception:
        return DirTree(root), root, 'working-tree'


# ====================================================================== which files
def _kind(path):
    low = path.lower()
    if low.endswith(DOC_EXT):
        return 'doc'
    if low.endswith(CODE_EXT):
        return 'code'
    if low.endswith(DECK_EXT):
        return 'deck'
    if low.endswith('.json') and re.search(r'schema|example|sample|recipe', low):
        return 'json'
    return None


def _priority(path, kind):
    parts = path.lower().split('/')
    name, dirs = parts[-1], parts[:-1]
    if not dirs and name.startswith('readme'):
        tier = 0
    elif kind == 'doc':
        tier = 1 if len(dirs) <= 2 else 2
    elif any(d in EXAMPLE_DIRS for d in dirs) or kind in ('json', 'deck'):
        tier = 1
    elif any(d in TEST_DIRS for d in dirs) or re.match(r'(test_|.*_test\.|.*\.test\.|.*\.spec\.)', name):
        tier = 4
    else:
        tier = 3
    if any(d in LOW_VALUE for d in dirs) or set(re.split(r'[-_.]', name)) & LOW_NAME:
        tier += 2
    return (tier, len(dirs), path)


def _nested_licence_dirs(tree, paths, root_holders):
    """sub-folders that carry their own licence: skip them when that licence is not permissive, or when the copyright
    holder differs from the repo's own (vendored / third-party code, e.g. a ported library)"""
    skip = {}
    for p in paths:
        if '/' in p and LICENCE_FILE.match(p.split('/')[-1]):
            d = p.rsplit('/', 1)[0]
            try:
                text = tree.read(p).decode('utf-8', 'replace')
            except Exception:
                continue
            spdx, kind = classify_licence(text)
            holders = {_holder(c) for c in copyright_lines(text)}
            if kind != 'permissive':
                skip[d] = f'own licence {spdx} ({kind})'
            elif holders and root_holders and not (holders & root_holders):
                skip[d] = f'third-party code ({"; ".join(sorted(holders))[:80]})'
    return skip


def _holder(c):
    s = re.sub(r'(?i)copyright|\(c\)|©|all rights reserved\.?|[0-9]{4}(\s*[-,]\s*[0-9]{4})*', ' ', c)
    return re.sub(r'\s+', ' ', s).strip(' .,').lower()


def _drop_reason(path, data, kind):
    if b'\0' in data[:8000]:
        return 'binary'
    text = data.decode('utf-8', 'replace')
    if text.count('�') > 20:
        return 'binary'
    if kind == 'json' and len(data) > MAX_JSON:
        return 'huge'
    lines = text.splitlines() or ['']
    longest = max(len(l) for l in lines)
    avg = len(text) / len(lines)
    if kind in ('code', 'json') and (avg > 200 or (longest > 1500 and len(lines) < 30)):
        return 'minified'
    if kind == 'doc' and longest > 20000:
        return 'minified'
    if GENERATED.search(text[:600]):
        return 'generated'
    return None


# ====================================================================== chunking
def _pack_pieces(pieces, limit=MAX_CHUNK):
    """[(title, text)] -> merge tiny neighbours with the same title root, split big ones on blank lines / lines"""
    out = []
    for title, text in pieces:
        text = text.strip('\n')
        if not text.strip():
            continue
        if out and len(out[-1][1]) + len(text) < limit // 2 and (len(text) < 120 or len(out[-1][1]) < 120):
            t1 = out[-1][0]                                    # tiny piece: join it to its neighbour, keep both names
            t = (t1 if title in ('', t1, 'module') else title if t1 in ('', 'module') or title.startswith(t1)
                 else f'{t1}, {title}')
            out[-1] = (t, out[-1][1] + '\n\n' + text)
            continue
        if len(text) <= limit:
            out.append((title, text))
            continue
        cur = ''
        for block in re.split(r'(\n\s*\n)', text):
            while len(block) > limit:                         # one very long block: cut on lines
                cut = block.rfind('\n', 0, limit)
                cut = cut if cut > limit // 3 else limit
                if cur:
                    out.append((title, cur.strip('\n')))
                    cur = ''
                out.append((title, block[:cut].strip('\n')))
                block = block[cut:]
            if len(cur) + len(block) > limit and cur.strip():
                out.append((title, cur.strip('\n')))
                cur = ''
            cur += block
        if cur.strip():
            out.append((title, cur.strip('\n')))
    return out


def chunk_markdown(text):
    pieces, stack, cur, fence = [], [], [], False
    def flush():
        if cur:
            pieces.append((' > '.join(stack), '\n'.join(cur)))
    for line in text.splitlines():
        if line.lstrip().startswith(('```', '~~~')):
            fence = not fence
        m = None if fence else re.match(r'(#{1,6})\s+(.+?)\s*#*\s*$', line)
        if m:
            flush()
            cur = []
            lvl = len(m.group(1))
            stack = stack[:lvl - 1] + [re.sub(r'[*_`\[\]]', '', m.group(2)).strip()]
        cur.append(line)
    flush()
    return _pack_pieces(pieces)


def chunk_rst(text):
    lines, md = text.splitlines(), []
    marks = {}
    i = 0
    while i < len(lines):
        l = lines[i]
        nxt = lines[i + 1] if i + 1 < len(lines) else ''
        if l.strip() and re.fullmatch(r'([=\-~^"\'`#*+])\1{2,}', nxt.strip()) and len(nxt.strip()) >= len(l.strip()) - 2:
            lvl = marks.setdefault(nxt.strip()[0], len(marks) + 1)
            md.append('#' * min(lvl, 6) + ' ' + l.strip())
            i += 2
            continue
        md.append(l)
        i += 1
    return chunk_markdown('\n'.join(md))


class _HTML(html.parser.HTMLParser):
    def __init__(self):
        super().__init__()
        self.out, self.skip = [], 0

    def handle_starttag(self, tag, attrs):
        if tag in ('script', 'style', 'svg', 'noscript'):
            self.skip += 1
        elif re.fullmatch(r'h[1-6]', tag):
            self.out.append('\n\n' + '#' * int(tag[1]) + ' ')
        elif tag in ('p', 'div', 'br', 'li', 'tr', 'section', 'pre'):
            self.out.append('\n\n' if tag != 'li' else '\n- ')

    def handle_endtag(self, tag):
        if tag in ('script', 'style', 'svg', 'noscript'):
            self.skip = max(0, self.skip - 1)
        elif re.fullmatch(r'h[1-6]', tag):
            self.out.append('\n\n')

    def handle_data(self, data):
        if not self.skip:
            self.out.append(re.sub(r'\s+', ' ', data))


def chunk_html(text):
    p = _HTML()
    p.feed(text)
    md = re.sub(r'\n[ \t]+', '\n', ''.join(p.out))
    md = re.sub(r'\n{3,}', '\n\n', md)
    md = re.sub(r'(#+ )\s*\n+', r'\1', md)
    return chunk_markdown(md)


def chunk_text(text):
    return _pack_pieces([('', p) for p in re.split(r'\n\s*\n', text)])


def chunk_python(text):
    import ast
    try:
        tree = ast.parse(text)
    except (SyntaxError, ValueError):
        return chunk_text(text)
    lines = text.splitlines()
    pieces, pos = [], 0
    for node in tree.body:
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            continue
        start = min([node.lineno] + [d.lineno for d in node.decorator_list]) - 1
        while start > pos and lines[start - 1].lstrip().startswith('#'):
            start -= 1                                         # comments right above belong to it
        if start > pos:
            pieces.append(('module', '\n'.join(lines[pos:start])))
        end = node.end_lineno
        kind = 'class' if isinstance(node, ast.ClassDef) else 'def'
        body = '\n'.join(lines[start:end])
        if kind == 'class' and len(body) > MAX_CHUNK:          # big class: header + one chunk per method
            subs = [n for n in node.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))]
            first = min([s.lineno for s in subs] + [end + 1]) - 1
            first = min([first] + [d.lineno - 1 for s in subs for d in s.decorator_list])
            pieces.append((f'class {node.name}', '\n'.join(lines[start:first])))
            for s in subs:
                s0 = min([s.lineno] + [d.lineno for d in s.decorator_list]) - 1
                pieces.append((f'{node.name}.{s.name}', '\n'.join(lines[s0:s.end_lineno])))
        else:
            pieces.append((f'{kind} {node.name}', body))
        pos = end
    if pos < len(lines):
        pieces.append(('module', '\n'.join(lines[pos:])))
    return _pack_pieces(pieces)


_ITEM = {
    'rs': (re.compile(r'^(pub(\([^)]*\))?\s+)?(async\s+|unsafe\s+|const\s+|extern\s+"C"\s+)*(fn|struct|enum|trait|impl|mod|const|static|type|macro_rules!)\b'),
           re.compile(r'^\s{4}(pub(\([^)]*\))?\s+)?(async\s+|unsafe\s+|const\s+)*fn\s')),
    'js': (re.compile(r'^(export\s+)?(default\s+)?(async\s+)?(function\*?|class|const|let|var|interface|type|enum|abstract\s+class)\b'),
           re.compile(r'^\s{2,4}(public\s+|private\s+|protected\s+|static\s+|async\s+|get\s+|set\s+|readonly\s+)*[A-Za-z_$][\w$]*\s*(<[^>]*>)?\([^;]*$')),
}
_NAME = re.compile(r'(?:fn|struct|enum|trait|impl(?:<[^>]*>)?|mod|const|static|type|function\*?|class|let|var|interface)\s+([A-Za-z_$][\w$:<>, ]*)')


def chunk_code(text, lang):
    top, inner = _ITEM[lang]
    lines = text.splitlines()
    starts = [0]
    for i, l in enumerate(lines):
        if i and top.match(l):
            j = i
            while j > starts[-1] and re.match(r'\s*(///?|/\*\*|\*|#\[|@\w)', lines[j - 1]):
                j -= 1
            if j > starts[-1]:
                starts.append(j)
    starts.append(len(lines))
    pieces = []
    for a, b in zip(starts, starts[1:]):
        seg = lines[a:b]
        head = next((l for l in seg if top.match(l)), '')
        m = _NAME.search(head)
        title = (m.group(0).split('(')[0].split('{')[0].strip()[:60]) if m else 'module'
        body = '\n'.join(seg)
        if len(body) > MAX_CHUNK:                              # impl / class: cut at member functions
            cuts = [0] + [k for k, l in enumerate(seg) if k and inner.match(l)] + [len(seg)]
            for c0, c1 in zip(cuts, cuts[1:]):
                sub = seg[c0:c1]
                mm = re.search(r'fn\s+(\w+)|([A-Za-z_$][\w$]*)\s*(<[^>]*>)?\(', sub[0]) if c0 else None
                name = (mm.group(1) or mm.group(2)) if mm else ''
                pieces.append((title + ('::' + name if name else ''), '\n'.join(sub)))
        else:
            pieces.append((title, body))
    return _pack_pieces(pieces)


def chunk_deck(text, keep=10):
    """solver input deck (Radioss /KEYWORD, Abaqus *KEYWORD, Nastran cards): one entry per keyword block, keeping its
    header, comments and first lines; long node / element lists are cut (they hold no knowledge)"""
    blocks, cur = [], []
    for line in text.splitlines():
        if line[:1] in ('/', '*') and not line.startswith('**') and cur:
            blocks.append(cur)
            cur = []
        cur.append(line.rstrip())
    if cur:
        blocks.append(cur)
    pieces = []
    for b in blocks:
        body = [l for l in b[1:] if l.strip()]
        txt = '\n'.join([b[0]] + body[:keep]) + (f'\n... (+{len(body) - keep} more lines)' if len(body) > keep else '')
        pieces.append((b[0][:60].strip(), txt))
    return _pack_pieces(pieces)


def chunk_file(path, text):
    low = path.lower()
    if low.endswith(('.md', '.markdown')):
        return chunk_markdown(text)
    if low.endswith('.rst'):
        return chunk_rst(text)
    if low.endswith(('.html', '.htm')):
        return chunk_html(text)
    if low.endswith('.py'):
        return chunk_python(text)
    if low.endswith(DECK_EXT):
        return chunk_deck(text)
    if low.endswith('.rs'):
        return chunk_code(text, 'rs')
    if low.endswith(('.ts', '.tsx', '.js', '.jsx', '.mjs')):
        return chunk_code(text, 'js')
    return chunk_text(text)


# ====================================================================== near-duplicates (MinHash + LSH)
_P = (1 << 61) - 1
_AB = [((i * 0x9E3779B97F4A7C15 + 0x632BE59BD9B4E019) % _P | 1, (i * 0xC2B2AE3D27D4EB4F + 0x165667B19E3779F9) % _P) for i in range(1, 33)]


def _shingles(text, k=5):
    w = re.findall(r'\w+', text.lower())
    if len(w) <= k:
        return {zlib.crc32(' '.join(w).encode())}
    return {zlib.crc32(' '.join(w[i:i + k]).encode()) for i in range(len(w) - k + 1)}


def dedupe(chunks, threshold=0.85):
    """drop exact and near-duplicate chunks (Jaccard of 5-word shingles >= threshold); keeps the first seen"""
    seen_exact, buckets, kept, shingle_sets = set(), {}, [], []
    dropped = 0
    for c in chunks:
        norm = re.sub(r'\s+', ' ', c['text']).strip().lower()
        h = hashlib.sha1(norm.encode()).digest()
        if h in seen_exact or len(norm) < 40:
            dropped += 1
            continue
        sh = _shingles(norm)
        sig = [min(((a * x + b) % _P) for x in sh) for a, b in _AB]
        cands = set()
        bands = [(bi, tuple(sig[bi * 4:bi * 4 + 4])) for bi in range(8)]
        for key in bands:
            cands.update(buckets.get(key, ()))
        if any(len(sh & shingle_sets[j]) / max(1, len(sh | shingle_sets[j])) >= threshold for j in cands):
            dropped += 1
            continue
        seen_exact.add(h)
        idx = len(kept)
        kept.append(c)
        shingle_sets.append(sh)
        for key in bands:
            buckets.setdefault(key, []).append(idx)
    return kept, dropped


# ====================================================================== build
def build_pack(src, out_dir, cache_dir=None, private_only=False, max_kb=DEFAULT_BUDGET_KB, name=None, log=print):
    """one repo -> out_dir/<name>.sbpack. Returns a summary dict (with 'refused' and 'reason' when the licence says no)."""
    name = name or repo_name(src)
    tree, url, commit = open_repo(src, cache_dir, log)
    try:
        listing = tree.files()
        paths = [p for p, _ in listing]
        lic_files = {}
        for p in _licence_files(paths):
            try:
                lic_files[p] = tree.read(p).decode('utf-8', 'replace')
            except Exception:
                pass
        if not lic_files:
            spdx = _manifest_spdx(tree, set(paths))
            if spdx:
                lic_files['@spdx:' + spdx] = spdx
        lic = check_licence(lic_files)
        root_holders = {_holder(c) for c in lic['attribution']}         # from the LICENSE files only
        for p in ('NOTICE', 'NOTICE.md', 'NOTICE.txt'):                 # Apache NOTICE: keep its copyright lines
            if p in paths:
                lic['attribution'] += [c for c in copyright_lines(tree.read(p).decode('utf-8', 'replace')) if c not in lic['attribution']]
        if not lic['attribution']:
            lic['attribution'] = [f'{url} contributors']
        if not lic['allowed'] and not private_only:
            log(f'REFUSED {name}: {lic["reason"]}')
            return {'name': name, 'repo': url, 'refused': True, 'reason': lic['reason'], 'license': lic['license']}
        skip_dirs = _nested_licence_dirs(tree, paths, root_holders)
        stats = {'files_seen': len(listing), 'dropped': {}, 'skipped_subtrees': skip_dirs}

        def drop(why):
            stats['dropped'][why] = stats['dropped'].get(why, 0) + 1

        cands = []
        for p, size in listing:
            parts = p.split('/')
            kind = _kind(p)
            if kind is None:
                drop('not text' if not re.search(r'\.(md|txt|py|rs|js|ts)', p) else 'other')
                continue
            if any(d.lower() in SKIP_DIRS or d.startswith('.') for d in parts[:-1]) or \
                    (kind == 'code' and p.lower().endswith(('.js', '.mjs')) and any(d.lower() in WEB_ASSET_DIRS for d in parts[:-1])):
                drop('vendored/build')                                   # (web-asset JS is almost always a library)
                continue
            if any(p == d or p.startswith(d + '/') for d in skip_dirs):
                drop('sub-folder licence')
                continue
            if SKIP_NAME.match(parts[-1]) or LOCK_NAME.search(p):
                drop('licence/lock')
                continue
            if size is not None and size > MAX_FILE:
                drop('huge')
                continue
            cands.append((_priority(p, kind), p, kind))
        cands.sort()
        budget, used, chunks, raw_src = max_kb * 1024, 0, [], 0
        for _, p, kind in cands:
            if used >= budget:
                drop('over budget')
                continue
            try:
                data = tree.read(p)
            except Exception:
                drop('unreadable')
                continue
            if len(data) > MAX_FILE:
                drop('huge')
                continue
            why = _drop_reason(p, data, kind)
            if why:
                drop(why)
                continue
            text = data.decode('utf-8', 'replace').replace('\r\n', '\n')
            raw_src += len(data)
            pieces = chunk_file(p, text) if kind != 'json' else chunk_text(text)
            for i, (title, body) in enumerate(pieces, 1):
                chunks.append({'id': f'{name}:{p}#{i}', 'source': p, 'title': title or os.path.basename(p), 'text': body})
            used += len(text)
        n0 = len(chunks)
        chunks, ndup = dedupe(chunks)
        stats.update(files_kept=len({c['source'] for c in chunks}), chunks=len(chunks), near_duplicates_dropped=ndup,
                     chunks_before_dedupe=n0, source_bytes=raw_src)
    finally:
        tree.close()
    allowed = bool(lic['allowed'])
    pack = {'format': FORMAT, 'name': name, 'repo': url, 'commit': commit, 'license': lic['license'],
            'license_reason': lic['reason'], 'allowed_for_training': allowed, 'private_only': not allowed,
            'usage': 'ok: permissive licence, keep the attribution' if allowed else
                     'PRIVATE ONLY: do not use for training, do not redistribute',
            'attribution': lic['attribution'], 'built': time.strftime('%Y-%m-%d'), 'stats': stats, 'chunks': chunks}
    raw = json.dumps(pack, ensure_ascii=False, separators=(',', ':')).encode('utf-8')
    os.makedirs(out_dir, exist_ok=True)
    fn = os.path.join(out_dir, name + ('.sbpack' if allowed else '.private.sbpack'))
    buf = io.BytesIO()
    with gzip.GzipFile(fileobj=buf, mode='wb', compresslevel=9, mtime=0) as g:
        g.write(raw)
    with open(fn, 'wb') as f:
        f.write(buf.getvalue())
    gz = os.path.getsize(fn)
    log(f'{name}: {lic["license"]}{"" if allowed else " (PRIVATE ONLY)"} | {stats["files_kept"]} files -> {len(chunks)} chunks '
        f'({ndup} duplicates dropped) | text {raw_src / 1024:.0f} KB, pack JSON {len(raw) / 1024:.0f} KB -> gzip {gz / 1024:.0f} KB '
        f'({len(raw) / max(gz, 1):.1f}x) -> {fn}')
    return {'name': name, 'repo': url, 'file': fn, 'license': lic['license'], 'allowed_for_training': allowed,
            'chunks': len(chunks), 'raw_bytes': len(raw), 'gz_bytes': gz, 'source_bytes': raw_src}


def read_pack(path):
    with gzip.open(path, 'rt', encoding='utf-8') as f:
        return json.load(f)


def write_notice(out_dir):
    """packs/NOTICE.md: attribution for every pack in the folder"""
    rows = []
    for fn in sorted(os.listdir(out_dir)):
        if fn.endswith('.sbpack'):
            try:
                p = read_pack(os.path.join(out_dir, fn))
            except Exception:
                continue
            rows.append(f"## {p['name']}\n\n- Source: {p['repo']} (commit {p['commit'][:12]})\n- Licence: {p['license']}\n"
                        f"- Use: {p.get('usage', '')}\n" + ''.join(f'- {a}\n' for a in p['attribution']))
    text = ('# Third-party notices for ShipBrain repo packs\n\n'
            'Each .sbpack holds text chunks (docs and code excerpts) from the repository named below, under its own '
            'licence. Keep this file with the packs. Packs marked PRIVATE ONLY must not be shared or used for training.\n\n'
            + '\n'.join(rows))
    with open(os.path.join(out_dir, 'NOTICE.md'), 'w', encoding='utf-8') as f:
        f.write(text)
    return text


# ====================================================================== loading
def load_pack(path, kb, training_only=False):
    """add the chunks of one .sbpack to a knowledge.Knowledge; sources become repo:<name>/<path> so answers cite them.
    training_only=True skips packs that are not allowed for training. Returns the number of chunks added."""
    p = read_pack(path)
    if training_only and not p.get('allowed_for_training'):
        return 0
    name = p['name']
    for c in p['chunks']:
        src = c['source'] if c['source'].startswith('repo:') else f'repo:{name}/{c["source"]}'
        kb.add(src, c['text'], c.get('title', ''), id=c['id'])
    packs = getattr(kb, 'packs', None)
    if packs is None:
        packs = kb.packs = []
    packs.append({k: p[k] for k in ('name', 'repo', 'commit', 'license', 'allowed_for_training', 'attribution')})
    return len(p['chunks'])


def load_packs(folder, kb, training_only=False):
    n = 0
    for fn in sorted(os.listdir(folder)) if os.path.isdir(folder) else []:
        if fn.endswith('.sbpack'):
            n += load_pack(os.path.join(folder, fn), kb, training_only)
    return n


# ====================================================================== CLI
def main(argv=None):
    ap = argparse.ArgumentParser(prog='python -m shipbrain.repopack', description=__doc__.split('\n\n')[1],
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest='cmd', required=True)
    for cmd in ('build', 'add'):
        s = sub.add_parser(cmd, help='build packs for the given repos' if cmd == 'build' else 'add one or more repos to a packs folder')
        if cmd == 'add':
            s.add_argument('repos', nargs='+', help='git URL or local folder')
        s.add_argument('--repo', action='append', default=[], help='git URL or local folder (repeat)')
        s.add_argument('--out', default='packs')
        s.add_argument('--cache', default=None, help='where clones are kept (default ~/.cache/shipbrain/repos)')
        s.add_argument('--max-kb', type=int, default=DEFAULT_BUDGET_KB, help='text kept per repo, KB (docs first)')
        s.add_argument('--private-only', action='store_true',
                       help='build refused repos anyway, marked "do not use for training / do not redistribute"')
    ls = sub.add_parser('list', help='show the packs in a folder')
    ls.add_argument('folder', nargs='?', default='packs')
    a = ap.parse_args(argv)
    if a.cmd == 'list':
        tot = 0
        for fn in sorted(os.listdir(a.folder)):
            if fn.endswith('.sbpack'):
                p = read_pack(os.path.join(a.folder, fn))
                sz = os.path.getsize(os.path.join(a.folder, fn))
                tot += sz
                print(f"{fn:40s} {sz / 1024:8.0f} KB  {len(p['chunks']):6d} chunks  {p['license']:24s} "
                      f"{'training ok' if p['allowed_for_training'] else 'PRIVATE ONLY'}  {p['repo']}")
        print(f'total {tot / 1024:.0f} KB')
        return 0
    repos = list(a.repo) + list(getattr(a, 'repos', []))
    if not repos:
        ap.error('give at least one --repo')
    results, rc = [], 0
    for r in repos:
        try:
            results.append(build_pack(r, a.out, a.cache, a.private_only, a.max_kb))
        except Exception as e:
            print(f'FAILED {r}: {type(e).__name__}: {e}')
            rc = 1
    if os.path.isdir(a.out):
        write_notice(a.out)
    built = [x for x in results if not x.get('refused')]
    if built:
        raw, gz = sum(x['raw_bytes'] for x in built), sum(x['gz_bytes'] for x in built)
        print(f'{len(built)} pack(s): {raw / 1024:.0f} KB JSON -> {gz / 1024:.0f} KB compressed; NOTICE.md updated in {a.out}')
    for x in results:
        if x.get('refused'):
            print(f'not packed: {x["name"]} - {x["reason"]}')
    return rc


if __name__ == '__main__':
    sys.exit(main())
