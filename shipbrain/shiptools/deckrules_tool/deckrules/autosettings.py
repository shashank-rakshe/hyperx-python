"""Rule 4c (step 1) - the build settings come from Rules 1-4, not from a hand-written settings file.  Offline, universal.

  python -m deckrules.autosettings FOLDER NAME [--out settings_auto.json]

frame_spacing_mm  : the FRAME SPACE written in the drawing (Step 2 / ask.spacing)
frame0_x_mm       : X of frame 0 from the frame anchor (GA / frame table answer / drawing writes frame 0 or negative frames = owner rule v2.105)
plan_heights_mm   : deck heights A/B found by Rule 3 / ask (deckrules_deck_details.csv), written first, correlated second
section_aliases   : a height-only designation ('150 U.A') that Rule 3 filled from ONE written full size (prov correlated(...)) - ambiguous ones are not guessed
Each value carries its source in '<key>_source'; anything not found is left out (the builder then uses its own default or reports it)."""
import csv, json, os, argparse, collections
from . import ask as A


def build(folder, name):
    T = {n: A._read(os.path.join(folder, n + '_step3_views.csv')) for n in A.drawings(folder)}
    SP = A.spacing(folder, T)
    AN = A.anchors(folder, T, SP)
    s = {'_note': 'generated by deckrules.autosettings from Rules 1-4 (no hand-written values)', 'mirror_missing_side': False}
    sp = SP.get(name)
    if sp:
        s['frame_spacing_mm'] = int(sp)
        s['frame_spacing_source'] = 'FRAME SPACE written in the drawing'
    ans = A.load_answers(folder)
    cfn, csrc, nodes = A.chain_x(folder, T, name, ans, SP)
    if cfn:                               # owner rule v2.106: X of a frame = sum of the spacings written between the frame labels (all drawings of the hull)
        tab = {}
        for f in range(-20, 140):
            v = cfn(f)
            if v is not None:
                tab[str(f)] = round(v, 1)
        s['frame_table'] = tab
        s['frame_table_source'] = csrc
        s.pop('frame_spacing_mm', None)
    elif name in AN and sp:
        fr, x, src = AN[name]
        s['frame0_x_mm'] = float(x - fr * sp)
        s['frame0_source'] = src
    dd = os.path.join(folder, 'deckrules_deck_details.csv')
    h = {}
    if os.path.exists(dd):
        hull = A.hull_of(name) or ''
        for r in A._read(dd):
            d = r['deck'].split('/', 1)
            if len(d) == 2 and d[0] == hull and r['z_mm']:
                h[d[1]] = int(r['z_mm'])
    s['plan_heights_mm'] = {k: v for k, v in h.items() if not k.startswith('NO.')}
    s['plan_heights_source'] = 'Rule 3 deck heights (deckrules_deck_details.csv)'
    al = {}
    for r in A._read(os.path.join(folder, name + '_step3_members.csv')):
        if r.get('prov', '').startswith('correlated') and r['shape'] and r['t'] and r['h']:
            al[r['text'].strip()] = ['L', int(r['h']), int(float(r['b'] or 0)), int(float(r['t'])), int(float(r['t2'] or r['t']))]
    s['section_aliases'] = al
    s['section_aliases_source'] = 'Rule 3 gap fill: height-only designation completed from one written full size'
    return s


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('folder')
    ap.add_argument('name')
    ap.add_argument('--out')
    a = ap.parse_args(argv)
    s = build(a.folder, a.name)
    out = a.out or os.path.join(a.folder, 'settings_%s_auto.json' % a.name)
    json.dump(s, open(out, 'w'), indent=1)
    print(out)
    print(json.dumps({k: v for k, v in s.items() if not k.endswith('_source') and k != 'section_aliases'}, indent=1))
    print('section_aliases', len(s['section_aliases']))


if __name__ == '__main__':
    main()
